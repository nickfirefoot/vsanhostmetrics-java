#!/usr/bin/env python3
"""Generate describe.xml, resources/resources.properties and CollectorKeys.java.

The Collector|* self-metric keys and labels come from the Python pack's
app/collector.py METRIC_KEYS (read with ast, so nothing is imported), so the
Java pack reports the same self-metrics. The connection fields mirror the
Python conf/describe.xml (vcenter_host, vcenter_user, verify_certs, the
vcenter_password credential) plus vcenter_port. There is NO Suite API
credential field: like the Python pack, the platform-injected per-instance
credential is used.

  python3 tools/gen_describe.py [--python-repo <Python 2.x pack> | $PYTHON_REPO] [--check]
"""
import argparse
import ast
import os
import sys
from xml.sax.saxutils import escape, quoteattr

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUTS = {"describe": os.path.join(REPO, "describe.xml"),
        "props": os.path.join(REPO, "resources", "resources.properties"),
        "java": os.path.join(REPO, "src", "com", "cptvsan", "adapter", "CollectorKeys.java")}

VERIFY_DESC = ("Set to false unless the VMCA root (or the issuing CA) has been accepted by the "
               "platform at Validate Connection. vCenter presents a VMCA-issued certificate. With "
               "it true, the server field must hold the FQDN rather than an IP.")


def metric_keys(py):
    with open(os.path.join(py, "app", "collector.py")) as f:
        for n in ast.parse(f.read()).body:
            if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "METRIC_KEYS":
                return ast.literal_eval(n.value)
    raise SystemExit("METRIC_KEYS not found")


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(keys):
    attrs, props = [], []
    nk = 12
    for k, label in keys.items():
        attrs.append(f'\t\t\t\t<ResourceAttribute key="{k}" nameKey="{nk}" dataType="float" '
                     f'isProperty="false" defaultMonitored="true"/>')
        props.append(f"{nk}={label}")
        nk += 1
    describe = f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  vSAN Host Metrics 3.0.0 (Java GENERAL adapter). GENERATED by tools/gen_describe.py.

  The ONLY kind this pack declares is its adapter instance (type 7). Every vSAN
  metric is pushed onto VMWARE ClusterComputeResource / HostSystem / VirtualMachine
  objects through the Suite API under "cptvsan|..." keys; a pak cannot declare keys
  for another adapter's kinds, so they are not declared here. No object other than
  the adapter instance and no relationship is ever reported.

  adapter kind key vsanhostmetrics (the factory builder requires lowercase) so its dashboards and
  views keep working. Same identifier names (vcenter_host, vcenter_user,
  verify_certs, credential vcenter_password); vcenter_port is new. The Suite API
  credential is the one the platform injects for the instance: no field.
-->
<AdapterKind xmlns="http://schemas.vmware.com/vcops/schema"
             xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
             key="vsanhostmetrics"
             nameKey="1"
             version="1"
             xsi:schemaLocation="http://schemas.vmware.com/vcops/schema describeSchema.xsd">

	<CredentialKinds>
		<CredentialKind key="vsan_vc_credential" nameKey="2">
			<CredentialField key="vcenter_password" nameKey="3" type="string" required="true" password="true" dispOrder="1"/>
		</CredentialKind>
	</CredentialKinds>

	<ResourceKinds>

		<!-- The adapter instance: one per vCenter. monitoringInterval is minutes. -->
		<ResourceKind key="vsanhostmetrics" nameKey="4" type="7"
		              credentialKind="vsan_vc_credential"
		              monitoringInterval="5">
			<ResourceIdentifier key="vcenter_host" nameKey="5" type="string"
			                    required="true" dispOrder="1" identType="1"/>
			<ResourceIdentifier key="vcenter_port" nameKey="6" type="string"
			                    required="false" dispOrder="2" default="443" identType="2"/>
			<ResourceIdentifier key="vcenter_user" nameKey="7" type="string"
			                    required="true" dispOrder="3" identType="1"/>
			<ResourceIdentifier key="verify_certs" nameKey="8" type="string"
			                    required="true" dispOrder="4" default="true" enum="true" identType="1">
				<enum value="true" nameKey="9" default="true"/>
				<enum value="false" nameKey="10" default="false"/>
			</ResourceIdentifier>

			<!-- Self-metrics, reported on the adapter instance. -->
			<ResourceGroup key="Collector" nameKey="11" instanced="false">
{chr(10).join(attrs)}
			</ResourceGroup>
		</ResourceKind>

	</ResourceKinds>

	<LicenseConfig enabled="false"/>

</AdapterKind>
'''
    properties = "\n".join([
        "# Display strings for vSAN Host Metrics, keyed by describe.xml nameKey. GENERATED.",
        "", "1=vSAN Host Metrics", "2=vCenter credential", "3=vCenter password",
        "4=vSAN Host Metrics Adapter Instance",
        "5=vCenter Server",
        "5.description=FQDN of the vCenter Server managing the vSAN clusters. Example: "
        "vc01.example.com -- NOT an IP address and NOT a URL. vCenter 8.0 Update 3 or later (or "
        "9.0 or later) is required: this pack uses the vSphere JSON API. It must be the same "
        "vCenter the VMware vSphere adapter collects, or no metric has an object to land on.",
        "6=vCenter port", "6.description=HTTPS port of the vCenter Server. Default 443.",
        "7=vCenter username",
        "7.description=Must include the domain. Example: vsanmon@vsphere.local. Read-only is "
        "sufficient: System.View and System.Read propagated from the vCenter root.",
        "8=Verify vCenter certificate", "8.description=" + VERIFY_DESC,
        "9=true", "10=false", "11=Collector"] + props + [""])
    java = ["// GENERATED by tools/gen_describe.py from the Python pack's collector.METRIC_KEYS -- DO NOT EDIT.",
            "package com.cptvsan.adapter;", "", "import java.util.Collections;",
            "import java.util.LinkedHashMap;", "import java.util.Map;", "",
            "/** The Collector|* self-metric keys and labels, the same as the Python pack. */",
            "final class CollectorKeys {", "", "    private CollectorKeys() {", "    }", "",
            "    static final Map<String, String> METRIC_KEYS;", "", "    static {",
            "        Map<String, String> m = new LinkedHashMap<>();"]
    java += [f"        m.put({q(k)}, {q(v)});" for k, v in keys.items()]
    java += ["        METRIC_KEYS = Collections.unmodifiableMap(m);", "    }", "}", ""]
    return {"describe": describe, "props": properties, "java": "\n".join(java)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python-repo", default=os.environ.get("PYTHON_REPO"), required=not os.environ.get("PYTHON_REPO"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = build(metric_keys(a.python_repo))
    stale = []
    for k, text in out.items():
        if a.check:
            if not os.path.exists(OUTS[k]) or open(OUTS[k]).read() != text:
                stale.append(OUTS[k])
        else:
            with open(OUTS[k], "w") as f:
                f.write(text)
            print("wrote", os.path.relpath(OUTS[k], REPO))
    if stale:
        print("stale:", *stale, file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
