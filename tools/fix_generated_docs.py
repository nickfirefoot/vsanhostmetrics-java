#!/usr/bin/env python3
"""Rewrite the generated inventory docs after every build.

The factory build regenerates docs/inventory-tree.{md,svg,excalidraw} and docs/README.md from
describe.xml. This pack deliberately creates no resource kinds (only its adapter instance), so
that output says "No traversal spec found" and "Resource kinds: 0": correct, but misleading,
because the data is on vCenter's own objects. This script runs after each build and replaces it:

  - inventory-tree.md / inventory-tree.svg: a "Where the data lives" page and diagram, with the
    cptvsan groups per target kind read from model/metric-tree.yaml;
  - README.md: the section is renamed and "Traversal spec / Resource kinds" is replaced by a
    one-line explanation;
  - inventory-tree.excalidraw is deleted.

    python3 tools/fix_generated_docs.py [--docs DIR]
"""
import argparse
import os
import re
import sys
from xml.sax.saxutils import escape

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

KINDS = [("ClusterComputeResource", "Cluster"), ("HostSystem", "Host"),
         ("VirtualMachine", "Virtual machine")]
EXPLAIN = ("This pack creates no objects of its own except its adapter instance: it pushes "
           "`cptvsan|...` metrics onto vCenter's own cluster, host and virtual machine objects "
           "(see [Where the data lives](inventory-tree.md)).")


def groups():
    tree = yaml.safe_load(open(os.path.join(REPO, "model", "metric-tree.yaml")))
    out = {k: set() for k, _ in KINDS}
    for e in tree["entities"].values():
        out[e["target"]].add(e["group"])
    return {k: sorted(v) for k, v in out.items()}, tree


def svg(g):
    bg, panel, edge, ink, mute, acc = "#2b3137", "#363d45", "#6b7782", "#e9edf0", "#b6bfc8", "#8fd3ff"
    colw, gap, x0 = 300, 20, 20
    width = x0 * 2 + 3 * colw + 2 * gap
    top = 20
    inst_h = 54
    col_top = top + inst_h + 50
    rows = max(len(v) for v in g.values())
    col_h = 64 + rows * 20 + 14
    height = col_top + col_h + 50
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" '
         f'height="{height}" font-family="Segoe UI, Helvetica, Arial, sans-serif" role="img" '
         f'aria-label="Where the vSAN Host Metrics data lives">',
         '<title>Where the vSAN Host Metrics data lives</title>',
         f'<rect width="{width}" height="{height}" rx="8" fill="{bg}"/>',
         f'<defs><marker id="ar" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" '
         f'markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="{ink}"/></marker></defs>']
    iw = 600
    ix = (width - iw) // 2
    o.append(f'<rect x="{ix}" y="{top}" width="{iw}" height="{inst_h}" rx="6" fill="{panel}" '
             f'stroke="{edge}" stroke-dasharray="5 4"/>')
    o.append(f'<text x="{width // 2}" y="{top + 23}" text-anchor="middle" font-size="15" '
             f'font-weight="700" fill="{ink}">vSAN Host Metrics adapter instance</text>')
    o.append(f'<text x="{width // 2}" y="{top + 43}" text-anchor="middle" font-size="12" '
             f'fill="{mute}">the only object this pack creates; it pushes metrics onto the objects vCenter owns</text>')
    for i, (kind, label) in enumerate(KINDS):
        x = x0 + i * (colw + gap)
        cx = x + colw // 2
        o.append(f'<line x1="{width // 2}" y1="{top + inst_h}" x2="{cx}" y2="{col_top}" '
                 f'stroke="{ink}" stroke-width="1.5" marker-end="url(#ar)"/>')
        o.append(f'<rect x="{x}" y="{col_top}" width="{colw}" height="{col_h}" rx="6" '
                 f'fill="{panel}" stroke="{edge}"/>')
        o.append(f'<text x="{x + 14}" y="{col_top + 24}" font-size="14" font-weight="700" '
                 f'fill="{ink}">{escape(kind)}</text>')
        o.append(f'<text x="{x + 14}" y="{col_top + 42}" font-size="12" fill="{mute}">'
                 f'vCenter\'s own object, {len(g[kind])} cptvsan groups</text>')
        for j, grp in enumerate(g[kind]):
            o.append(f'<text x="{x + 14}" y="{col_top + 66 + j * 20}" font-size="12.5" '
                     f'font-family="Consolas, Menlo, monospace" fill="{acc}">cptvsan|{escape(grp)}</text>')
    o.append(f'<text x="{width // 2}" y="{height - 18}" text-anchor="middle" font-size="12" '
             f'fill="{mute}">Nothing is created or re-parented on these objects; the metrics '
             f'are added to them.</text>')
    o.append("</svg>")
    return "\n".join(o) + "\n"


def page(g, tree):
    n_ent = tree["entity_types"]
    rows = "\n".join(f"| `{k}` | {len(g[k])} | " + ", ".join(f"`{x}`" for x in g[k]) + " |"
                     for k, _ in KINDS)
    return f"""# Where the data lives: vSAN Host Metrics

> Generated by `tools/fix_generated_docs.py` after each build. Do not edit.

![Where the data lives](inventory-tree.svg)

This pack creates **no resource kinds** and no inventory tree of its own. The only object it
creates is its adapter instance. Everything it collects ({n_ent} vSAN Performance Service entity
types) is pushed as `cptvsan|...` metrics and properties onto objects that vCenter's own adapter
already owns:

| vCenter object | Groups | `cptvsan` groups on it |
|---|---|---|
{rows}

The pack does not create, move or re-parent any of these objects, and writes no relationships
(`ci/no_relationships.sh` enforces this). To find the data, open the vCenter cluster, host or
virtual machine in Operations and look under the `cptvsan` metric group. The views and
dashboards read it from the selected cluster through vCenter's own cluster, host and virtual
machine relationships.

The full list of metrics and properties is in [REFERENCE.md](../REFERENCE.md).
"""


def fix_readme(path):
    s = open(path).read()
    s = s.replace("## Inventory Tree", "## Where the data lives")
    s = s.replace("[Inventory Tree](inventory-tree.md) | Traversal spec, per-kind table with identifying keys |",
                  "[Where the data lives](inventory-tree.md) | Which vCenter objects carry the `cptvsan` metrics, and which groups |")
    s = s.replace("![Inventory Tree](inventory-tree.svg)", "![Where the data lives](inventory-tree.svg)")
    s = re.sub(r"- \*\*Traversal spec:\*\*[^\n]*\n- \*\*Resource kinds:\*\*[^\n]*",
               "- **Objects created:** " + EXPLAIN.replace("This pack creates", "this pack creates", 1), s)
    s = s.replace("The SVG diagram and per-kind table are regenerated on every\n> build;",
                  "The inventory page and diagram are rewritten after every\n> build by tools/fix_generated_docs.py;")
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--docs", default=os.path.join(REPO, "docs"))
    a = ap.parse_args()
    g, tree = groups()
    open(os.path.join(a.docs, "inventory-tree.svg"), "w").write(svg(g))
    open(os.path.join(a.docs, "inventory-tree.md"), "w").write(page(g, tree))
    rp = os.path.join(a.docs, "README.md")
    fixed = fix_readme(rp)
    open(rp, "w").write(fixed)
    x = os.path.join(a.docs, "inventory-tree.excalidraw")
    if os.path.exists(x):
        os.remove(x)
    print("docs fixed in", a.docs)


if __name__ == "__main__":
    sys.exit(main())
